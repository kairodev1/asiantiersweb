create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- 1. PLAYERS
-- ---------------------------------------------------------------------
create table if not exists public.players (
  id              bigint generated by default as identity primary key,
  ign             text not null,
  discord_id      text,
  overall_tier    text,
  overall_points  integer default 0 not null,
  sword_tier      text,
  sword_points    integer default 0 not null,
  axe_tier        text,
  axe_points      integer default 0 not null,
  mace_tier       text,
  mace_points     integer default 0 not null,
  diapot_tier     text,
  pot_points      integer default 0 not null,      -- DiaPot points
  nethpot_tier    text,
  nethpot_points  integer default 0 not null,
  smp_tier        text,
  smp_points      integer default 0 not null,
  crystal_tier    text,
  vanilla_points  integer default 0 not null,      -- Crystal points
  uhc_tier        text,
  uhc_points      integer default 0 not null,
  created_at      timestamptz default now() not null
);

-- Extra profile columns the CityDiscord bot writes (harmless if unused)
alter table public.players add column if not exists region        text;
alter table public.players add column if not exists account_type  text;
alter table public.players add column if not exists verified      boolean default false;
alter table public.players add column if not exists updated_at    timestamptz default now();

-- Tier must be one of the six supported tiers (or null / legacy 'Unranked')
do $$
declare
  cols text[] := array['overall_tier','sword_tier','axe_tier','mace_tier','diapot_tier',
                       'nethpot_tier','smp_tier','crystal_tier','uhc_tier'];
  c text;
begin
  foreach c in array cols loop
    execute format('alter table public.players drop constraint if exists %I', c || '_check');
    execute format(
      'alter table public.players add constraint %I check (%I is null or %I in (%L,%L,%L,%L,%L,%L,%L,%L,%L,%L,%L,%L,%L,%L) or %I = %L)',
      c || '_check', c, c, 'HT1','RHT1','LT1','RLT1','HT2','RHT2','LT2','RLT2','HT3','LT3','HT4','LT4','HT5','LT5', c, 'Unranked');
  end loop;
end $$;

-- Unique IGN (case-insensitive). Safe to re-run: skips if legacy duplicates exist.
do $$
begin
  if exists (select 1 from public.players group by lower(ign) having count(*) > 1) then
    raise notice 'Skipped unique IGN index: duplicate IGNs exist. Fix them, then re-run this script.';
  else
    create unique index if not exists players_ign_key on public.players (lower(ign));
  end if;
end $$;

-- One profile per Discord account. NULLs allowed (unlinked legacy rows).
-- Skips safely if an account is already attached to two profiles.
do $$
begin
  if exists (select 1 from public.players where discord_id is not null group by discord_id having count(*) > 1) then
    raise notice 'Skipped unique Discord index: a discord_id is linked to multiple players. Fix, then re-run.';
  else
    create unique index if not exists players_discord_id_key on public.players (discord_id);
  end if;
end $$;

create index if not exists players_points_idx on public.players (overall_points desc);

